SELECT EMPLOYEE_ID,
       FIRST_NAME,
       LAST_NAME,
       DEPARTMENT_ID
FROM HR.EMPLOYEES E
WHERE NOT EXISTS (
    SELECT 1
    FROM HR.DEPARTMENTS D
    WHERE D.DEPARTMENT_ID = E.DEPARTMENT_ID
);
--B
SELECT EMPLOYEE_ID,
       FIRST_NAME,
       LAST_NAME,
       DEPARTMENT_ID
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID NOT IN (
    SELECT DEPARTMENT_ID
    FROM HR.DEPARTMENTS
);
-- NOT EXISTS NULL olan DEPARTMENT_ID-ni də nəzərə alır.
-- NOT IN isə xarici DEPARTMENT_ID NULL olduqda
-- UNKNOWN qaytarır və həmin sətri nəticəyə daxil etmir.

