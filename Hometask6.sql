SELECT TO_CHAR(TO_DATE('2026/12/31', 'YYYY/MM/DD'), 'DD.MM.YYYY HH24:MI') AS A,
       TO_CHAR(TO_DATE('31-12-2026 23:59', 'DD-MM-YYYY HH24:MI'), 'DD.MM.YYYY HH24:MI') AS B,
       TO_CHAR(TO_DATE('20261231', 'YYYYMMDD'), 'DD.MM.YYYY HH24:MI') AS C,
       TO_CHAR(TO_DATE('December 31, 2026', 'Month DD, YYYY'), 'DD.MM.YYYY HH24:MI') AS D,
       TO_CHAR(TO_DATE('2026@12@31  08:30', 'YYYY@MM@DD  HH24:MI'), 'DD.MM.YYYY HH24:MI') AS E
FROM DUAL;

-- A, C və D saat 00:00 çıxdı.
-- Çünki həmin mətnlərdə saat və dəqiqə qeyd edilməyib.
-- B və E-də isə saat və dəqiqə verildiyi üçün
-- həmin vaxtlar nəticədə göstərilir.

