SELECT D.DEPARTMENT_ID,
       D.DEPARTMENT_NAME
FROM HR.DEPARTMENTS D
WHERE EXISTS (
    SELECT 1
    FROM HR.EMPLOYEES E
    WHERE E.DEPARTMENT_ID = D.DEPARTMENT_ID
      AND E.HIRE_DATE >= DATE '2007-01-01'
);

--B
SELECT DEPARTMENT_ID,
       DEPARTMENT_NAME
FROM HR.DEPARTMENTS
WHERE DEPARTMENT_ID IN (
    SELECT DEPARTMENT_ID
    FROM HR.EMPLOYEES
    WHERE HIRE_DATE >= DATE '2007-01-01'
);

