--A
SELECT FIRST_NAME,
       LAST_NAME,
       HIRE_DATE
FROM HR.EMPLOYEES
WHERE HIRE_DATE >= TO_DATE('01.07.2006', 'DD.MM.YYYY')
  AND HIRE_DATE < TO_DATE('01.01.2007', 'DD.MM.YYYY')
ORDER BY HIRE_DATE ASC;
--B
SELECT FIRST_NAME,
       LAST_NAME,
       HIRE_DATE
FROM HR.EMPLOYEES
WHERE HIRE_DATE BETWEEN
      TO_DATE('01.07.2006', 'DD.MM.YYYY')
      AND TO_DATE('31.12.2006', 'DD.MM.YYYY')
ORDER BY HIRE_DATE ASC;

-- HIRE_DATE-də saat da olsaydı, BETWEEN problemi yarada bilərdi.
-- Çünki TO_DATE('31.12.2006', 'DD.MM.YYYY') saatı 00:00 qəbul edir.
-- Buna görə 31 dekabr saat 00:00-dan sonrakı işçilər
-- nəticəyə daxil olmazdı.
-- a variantında isə 01.01.2007-dən kiçik şərti
-- 31 dekabrın bütün saatlarını əhatə edir.

