SELECT FIRST_NAME,
       TO_CHAR(SALARY, 'FM999999') AS MAAS,
       TO_CHAR(HIRE_DATE, 'HH24') AS SAAT
FROM HR.EMPLOYEES
WHERE TO_CHAR(HIRE_DATE, 'FMMonth') = 'May';


-- 1.'999' maskası maaşı göstərmək üçün kiçikdir.
--Daha böyük maska istifadə edilməlidir.
