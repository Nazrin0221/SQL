SELECT CONCAT(CONCAT(CONCAT(CONCAT(CONCAT(FIRST_NAME, ' '), LAST_NAME), ' ['), JOB_ID), ']'
) AS ISCI_KARTI,
       TO_CHAR(HIRE_DATE, 'Q') AS GIRIS_RUBU,
       TO_CHAR(HIRE_DATE, 'DDD') AS ILIN_GUNU
FROM HR.EMPLOYEES;
