SELECT FIRST_NAME,
       HIRE_DATE,
       TO_CHAR(TRUNC(HIRE_DATE, 'YEAR'), 'DD.MM.YYYY'
       ) AS ILIN_ILK_GUNU,
       TO_CHAR(ADD_MONTHS(TRUNC(HIRE_DATE, 'YEAR'), 12) - 1, 'DD.MM.YYYY'
       ) AS ILIN_SON_GUNU,
       ADD_MONTHS(TRUNC(HIRE_DATE, 'YEAR'), 12) - 1
       - TRUNC(HIRE_DATE) AS ILE_QALAN_GUN
FROM HR.EMPLOYEES;
