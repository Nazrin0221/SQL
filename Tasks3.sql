--Task 7

SELECT DEPARTMENT_ID,
       COUNT(*) AS ISCI_SAYI,
       TO_CHAR(MIN(HIRE_DATE), 'DD.MM.YYYY') AS ILK_ISCI_TARIX,
       TO_CHAR(MAX(HIRE_DATE), 'DD.MM.YYYY') AS SON_ISCI_TARIX,
       TRUNC(MAX(HIRE_DATE)) - TRUNC(MIN(HIRE_DATE)) AS GUN_FERQI
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID IS NOT NULL
GROUP BY DEPARTMENT_ID
ORDER BY DEPARTMENT_ID ASC;

--Task 8

SELECT 'EMP-' ||
       LPAD(EMPLOYEE_ID, 5, '0') ||
       '-' ||
       UPPER(SUBSTR(FIRST_NAME, 1, 1)) ||
       UPPER(SUBSTR(LAST_NAME, 1, 1)) AS KART_NO,

       LAST_NAME,

       LENGTH(EMAIL) AS EMAIL_UZUNLUQ,

       INSTR(LAST_NAME, 'a') AS ILK_HERF_YERI
FROM HR.EMPLOYEES
WHERE LAST_NAME LIKE '%a%';

--Task 9

SELECT TO_CHAR(HIRE_DATE, 'Q') AS RUB,
       TO_CHAR(HIRE_DATE, 'MM') AS AY_NO,
       TO_CHAR(HIRE_DATE, 'FMMonth') AS AY_ADI,
       COUNT(*) AS ISCI_SAYI,
       TO_CHAR(SUM(SALARY), 'FM$999,999,999') AS CEMI_MAAS
FROM HR.EMPLOYEES
GROUP BY TO_CHAR(HIRE_DATE, 'Q'),
         TO_CHAR(HIRE_DATE, 'MM'),
         TO_CHAR(HIRE_DATE, 'FMMonth')
ORDER BY RUB ASC, AY_NO ASC;

