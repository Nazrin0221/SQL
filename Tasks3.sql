--Task 1

SELECT FIRST_NAME,
UPPER(SUBSTR(FIRST_NAME, 1, 2)) || '-' || LOWER(SUBSTR(LAST_NAME, 1, 3)) AS KOD_AD,
       REPLACE(PHONE_NUMBER, '.', '') AS TELEFON_TEMIZ,
       LENGTH(FIRST_NAME || LAST_NAME) AS AD_UZUNLUQ
FROM HR.EMPLOYEES
ORDER BY AD_UZUNLUQ DESC;

--Task 2

SELECT FIRST_NAME,
       SALARY,
       CASE
           WHEN COMMISSION_PCT IS NOT NULL
           THEN TO_CHAR(COMMISSION_PCT * 100, 'FM999') || '%'
           ELSE 'Teyin edilmeyib'
       END AS KOMISSIYA_FAIZ,
       TO_CHAR(NVL(SALARY * COMMISSION_PCT, 0),
               'FM$999,999.00') AS BONUS_MEBLEG
FROM HR.EMPLOYEES
WHERE SALARY > 5000
ORDER BY SALARY DESC;

