SELECT FIRST_NAME,
       TO_CHAR(HIRE_DATE, 'DD-Mon-YYYY') AS ISE_GIRIS,
       TO_CHAR(NEXT_DAY(HIRE_DATE, 'MONDAY'),'DD.MM.YYYY')
       AS TELIM_TARIXI,
       NEXT_DAY(HIRE_DATE, 'MONDAY') - HIRE_DATE AS GOZLEME_GUNU
FROM HR.EMPLOYEES
WHERE JOB_ID IN ('IT_PROG', 'SA_REP');

