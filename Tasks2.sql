SELECT  FIRST_NAME, PHONE_NUMBER, SALARY, 
        CASE 
            WHEN PHONE_NUMBER LIKE  '515%' THEN  'Daxili xett'
            WHEN SALARY >= 10000 THEN 'Yuksek maasli'
            WHEN COMMISSION_PCT IS NOT NULL THEN 'Satis komandasi'
            ELSE 'Standart isci'
        END AS KATEQORIYA
FROM HR.EMPLOYEES;

--Task 8

SELECT FIRST_NAME, SALARY, COMMISSION_PCT, SALARY * NVL(COMMISSION_PCT, 0) * 3 AS RUBLUK_BONUS,
SALARY * 3 + SALARY * NVL(COMMISSION_PCT, 0) * 3 AS RUBLUK_UMUMI
FROM HR.EMPLOYEES
ORDER BY RUBLUK_UMUMI ASC;

--Task 9

SELECT E.FIRST_NAME, J.JOB_TITLE, E.SALARY, J.MIN_SALARY, J.MAX_SALARY,
       CASE WHEN SALARY = MAX_SALARY THEN  'Limite catib'
            WHEN MAX_SALARY - SALARY <= 2000 THEN 'Limite cox yaxin'
            WHEN SALARY < MIN_SALARY + 1000 THEN 'Baslangic seviyyede'
            ELSE 'Orta araliqda'
        END AS MAAS_VEZIYYETI
FROM HR.JOBS J
JOIN HR.EMPLOYEES E
ON J.JOB_ID = E.JOB_ID;

