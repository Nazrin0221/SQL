SELECT FIRST_NAME, LAST_NAME, HIRE_DATE,
        CASE WHEN HIRE_DATE < TO_DATE('2003-01-01', 'YYYY-MM-DD') THEN 'Veteran'
             WHEN HIRE_DATE < TO_DATE('2006-01-01', 'YYYY-MM-DD') THEN 'Tecrubeli'
             ELSE 'Yeni'
        END AS STAJ_QRUPU
FROM HR.EMPLOYEES;

--Task 2

SELECT DEPARTMENT_ID, DEPARTMENT_NAME,
       CASE DEPARTMENT_NAME
            WHEN 'Administration' THEN 'Idarəetmə'
            WHEN 'Marketing' THEN 'Marketinq'
            WHEN 'Purchasing' THEN 'Satinalma'
            WHEN 'Human Resources' THEN 'Insan Resurslari'
            ELSE 'Diger sobe'
        END AS SOBE_AZ
FROM HR.DEPARTMENTS;

