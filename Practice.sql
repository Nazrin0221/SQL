--Task 1

SELECT FIRST_NAME, LAST_NAME, SALARY, SALARY * 1.1 AS "YENI_MAAS" FROM HR.EMPLOYEES;

--Task 2

SELECT DISTINCT COUNTRY_ID FROM HR.LOCATIONS;

--Task 3

SELECT FIRST_NAME, DEPARTMENT_ID, SALARY FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID = 50 AND SALARY < 3000 
OR DEPARTMENT_ID = 80 AND SALARY > 10000;

--Task 4

SELECT JOB_TITLE, MIN_SALARY FROM HR.JOBS
WHERE MIN_SALARY BETWEEN 4000 AND 6000;

--Task 5

SELECT CITY, COUNTRY_ID FROM HR.LOCATIONS
WHERE COUNTRY_ID IN ('US', 'GB', 'CA');

--Task 6

SELECT FIRST_NAME, LAST_NAME FROM HR.EMPLOYEES
WHERE FIRST_NAME LIKE 'S____' AND LOWER(LAST_NAME) LIKE '%a%';

--Task 7

SELECT DEPARTMENT_NAME FROM HR.DEPARTMENTS
WHERE MANAGER_ID IS NULL;

--Task 8

SELECT JOB_TITLE, MAX_SALARY - MIN_SALARY AS "MAAS_FERQI" FROM HR.JOBS
ORDER BY MAAS_FERQI DESC
FETCH FIRST 3 ROW ONLY;

--Task 9

SELECT COUNT(FIRST_NAME) AS "ISCI_SAYI",
COUNT(COMMISSION_PCT) AS "KOMMISSIYA_ALANLAR",
ROUND(AVG(SALARY), 2) AS "ORTA_MAAS",
MAX(SALARY)-MIN(SALARY) AS "MAAS_FERQI"
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID = 80;

