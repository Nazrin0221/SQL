--Task 1

SELECT DEPARTMENT_ID, MAX(SALARY) AS MAKS_MAAS
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID IS NOT NULL
GROUP BY DEPARTMENT_ID
ORDER BY MAKS_MAAS DESC;

--Task 2

SELECT LOCATION_ID, COUNT(*) AS SOBE_SAYI
FROM HR.DEPARTMENTS
GROUP BY LOCATION_ID
ORDER BY SOBE_SAYI DESC;

--Task 3

SELECT E.FIRST_NAME, E.LAST_NAME, D.DEPARTMENT_NAME
FROM HR.EMPLOYEES E
JOIN HR.DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID;

--Task 4

SELECT JOB_ID, SUM(SALARY) AS UMUMI_MAAS
FROM HR.EMPLOYEES
GROUP BY JOB_ID
HAVING SUM(SALARY) > 30000;

--Task 5

SELECT DEPARTMENT_ID, MIN(SALARY) AS MIN_MAAS
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID IS NOT NULL
GROUP BY DEPARTMENT_ID
HAVING MIN(SALARY) > 4000
ORDER BY MIN_MAAS ASC;

--Task 6

SELECT J.JOB_TITLE, ROUND(AVG(E.SALARY), 2) AS ORTA_MAAS
FROM HR.EMPLOYEES E
JOIN HR.JOBS J
ON E.JOB_ID = J.JOB_ID
GROUP BY J.JOB_TITLE
HAVING AVG(SALARY) BETWEEN 6000 AND 12000;

--Task 7

SELECT JOB_TITLE
FROM HR.JOBS J
LEFT JOIN HR.EMPLOYEES E
ON J.JOB_ID = E.JOB_ID
WHERE EMPLOYEE_ID IS NULL;

--Task 8

SELECT D.DEPARTMENT_NAME, COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES E
JOIN HR.DEPARTMENTS D ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_NAME
HAVING COUNT(*) > 4;

--Task 9

SELECT DEPARTMENT_ID, MANAGER_ID, COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES
WHERE (DEPARTMENT_ID IS NOT NULL) AND (MANAGER_ID IS NOT NULL)
GROUP BY DEPARTMENT_ID, MANAGER_ID;

--Task 10

SELECT L.CITY, SUM(E.SALARY) AS UMUMI_MAAS
FROM HR.EMPLOYEES E
JOIN HR.DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
JOIN HR.LOCATIONS L
ON D.LOCATION_ID = L.LOCATION_ID
GROUP BY L.CITY
HAVING SUM(E.SALARY) > 20000
ORDER BY UMUMI_MAAS DESC;

--Task 11

SELECT L.CITY, COUNT(D.DEPARTMENT_ID) AS SOBE_SAYI
FROM HR.LOCATIONS L
LEFT JOIN HR.DEPARTMENTS D
ON L.LOCATION_ID = D.LOCATION_ID
GROUP BY L.CITY
ORDER BY SOBE_SAYI DESC;

--Task 12

SELECT D.DEPARTMENT_NAME,
       COUNT(*) AS ISCI_SAYI,
       ROUND(AVG(E.SALARY)) AS ORTA_MAAS
FROM HR.EMPLOYEES E
JOIN HR.DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
WHERE E.SALARY > 5000
GROUP BY D.DEPARTMENT_NAME
HAVING COUNT(*) > 2;

--Task 13

SELECT J.JOB_TITLE, D.DEPARTMENT_NAME, COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES E
JOIN HR.DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
JOIN HR.JOBS J
ON E.JOB_ID = J.JOB_ID
GROUP BY J.JOB_TITLE, D.DEPARTMENT_NAME
ORDER BY J.JOB_TITLE ASC;
