--Task 1

SELECT MANAGER_ID, COUNT(FIRST_NAME) AS ISCI_SAYI 
FROM HR.EMPLOYEES
GROUP BY MANAGER_ID
ORDER BY ISCI_SAYI DESC;

--Task 2

SELECT COUNTRY_ID, COUNT(*) AS OFIS_SAYI
FROM HR.LOCATIONS
GROUP BY COUNTRY_ID
ORDER BY OFIS_SAYI DESC;

--Task 3

SELECT E.FIRST_NAME, E.LAST_NAME, J.JOB_TITLE
FROM HR.EMPLOYEES E
JOIN HR.JOBS J
ON E.JOB_ID = J.JOB_ID;

--Task 4

SELECT DEPARTMENT_ID, ROUND(AVG(SALARY), 2) AS ORTA_MAAS
FROM HR.EMPLOYEES
GROUP BY DEPARTMENT_ID
HAVING AVG(SALARY) > 8000;

--Task 5

SELECT DEPARTMENT_ID, COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES
WHERE SALARY >= 3000
GROUP BY DEPARTMENT_ID
HAVING COUNT(*) > 3;

--Task 6
SELECT HR.JOBS.JOB_TITLE, COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES
JOIN HR.JOBS
ON HR.EMPLOYEES.JOB_ID = HR.JOBS.JOB_ID
GROUP BY JOB_TITLE
ORDER BY ISCI_SAYI DESC;

--Task 7

SELECT L.CITY, L.COUNTRY_ID
FROM HR.LOCATIONS L
LEFT JOIN HR.DEPARTMENTS D
ON L.LOCATION_ID = D.LOCATION_ID
WHERE D.DEPARTMENT_ID IS NULL;

--Task 8

SELECT J.JOB_TITLE, AVG(E.SALARY) AS ORTA_MAAS
FROM HR.EMPLOYEES E
JOIN HR.JOBS J ON E.JOB_ID = J.JOB_ID
GROUP BY J.JOB_TITLE
HAVING AVG(E.SALARY) > 10000;
--E.JOB_ID = J.JOB_ID, JOB_ID sütununun hansı cədvələ aid olduğunu göstərməliyik.
--WHERE əvəzini HAVİNG istifadə etməliyik, çünki AVG() aqreqat funksiyalar üçün HAVING istifadə olunur.
--GROUP BY HAVİNG-dən əvvəl işlənir.

--Task 9

SELECT L.CITY, COUNT(*) AS ISCI_SAYI, ROUND(AVG(SALARY)) AS ORTA_MAAS
FROM HR.EMPLOYEES E
JOIN HR.DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
JOIN HR.LOCATIONS L
ON D.LOCATION_ID = L.LOCATION_ID
GROUP BY CITY
HAVING COUNT(*) > 5
ORDER BY ISCI_SAYI DESC;

--Task 10

SELECT DEPARTMENT_NAME, COUNT(*) AS ISCI_SAYI
FROM HR.DEPARTMENTS D
LEFT JOIN HR.EMPLOYEES E
ON D.DEPARTMENT_ID = E.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_NAME
ORDER BY ISCI_SAYI DESC, DEPARTMENT_NAME ASC;

