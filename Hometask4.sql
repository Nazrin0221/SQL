SELECT FIRST_NAME, LAST_NAME
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID IN (SELECT DEPARTMENT_ID
                       FROM HR.DEPARTMENTS
                       WHERE DEPARTMENT_NAME IN ('Sales', 'IT'));

-- '=' evəzinə 'IN' istifadə edilməlidir, çünki subquery birdən çox DEPARTMENT_ID qaytara bilər.
-- Subquery-də iki sütün deyil, yalnız DEPARTMENT_ID seçilməlidir.
--'Sales' yazılmalıdır.

