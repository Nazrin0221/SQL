--Task 10

SELECT M.FIRST_NAME, M.LAST_NAME, COUNT(*) AS TABE_SAYI,
ROUND(AVG(E.SALARY)) AS TABELERIN_ORTA_MAAS
FROM HR.EMPLOYEES E
JOIN HR.EMPLOYEES M
ON E.MANAGER_ID = M.EMPLOYEE_ID
GROUP BY M.FIRST_NAME, M.LAST_NAME, M.EMPLOYEE_ID
HAVING COUNT(*) > 5
ORDER BY TABE_SAYI DESC;
