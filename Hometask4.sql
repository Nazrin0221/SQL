SELECT EMPLOYEE_ID, FIRST_NAME, LAST_NAME
FROM HR.EMPLOYEES
WHERE EMPLOYEE_ID IN (SELECT MANAGER_ID
                      FROM HR.EMPLOYEES
                      WHERE MANAGER_ID IS NOT NULL);

