SELECT E.FIRST_NAME, E.LAST_NAME, M.FIRST_NAME AS MENECER_ADI,
M.LAST_NAME AS MENECER_SOYADI
FROM HR.EMPLOYEES E
JOIN HR.EMPLOYEES M
ON E.MANAGER_ID = M.EMPLOYEE_ID;

--Task 2

SELECT E.FIRST_NAME, E.LAST_NAME, M.FIRST_NAME AS MENECER_ADI,
M.LAST_NAME AS MENECER_SOYADI
FROM HR.EMPLOYEES E
LEFT JOIN HR.EMPLOYEES M
ON E.MANAGER_ID = M.EMPLOYEE_ID;
